import { createHash } from 'node:crypto';
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

function fail(message) {
  console.error(`[linux-canary] ${message}`);
  if (process.env.GITHUB_ACTIONS === 'true') {
    console.error(`::error title=Linux canary verification::${message}`);
  }
  process.exit(1);
}

function requireFile(path, minimumBytes = 1) {
  if (!existsSync(path)) fail(`missing required artifact: ${path}`);
  const size = statSync(path).size;
  if (size < minimumBytes) fail(`${path} is unexpectedly small (${size} bytes)`);
  return size;
}

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

const version = (process.env.CANARY_VERSION ?? process.argv[2] ?? '').trim();
const match = version.match(/^\d+\.\d+\.\d+-(alpha|beta|rc)\.\d+$/);
if (!match) fail(`expected a prerelease version, got ${JSON.stringify(version)}`);

const packageVersion = JSON.parse(readFileSync('package.json', 'utf8')).version;
if (packageVersion !== version) {
  fail(`package.json is ${packageVersion}; expected stamped version ${version}`);
}

const channel = match[1];
const appImageName = `WraeclastLedger-${version}-x86_64.AppImage`;
const appImagePath = join('dist', appImageName);
const blockmapPath = `${appImagePath}.blockmap`;
const metadataPath = join('dist', `${channel}-linux.yml`);
const stableMetadataPath = join('dist', 'latest-linux.yml');
const packagedUpdaterConfigPath = join('dist', 'packaged-app-update.yml');

const appImageBytes = requireFile(appImagePath, 50 * 1024 * 1024);
const blockmapBytes = requireFile(blockmapPath, 100);
requireFile(metadataPath, 100);
requireFile(packagedUpdaterConfigPath, 20);
if (existsSync(stableMetadataPath)) {
  fail('stable latest-linux.yml was generated by a prerelease build');
}

const packagedUpdaterConfig = readFileSync(packagedUpdaterConfigPath, 'utf8');
const packagedChannel = packagedUpdaterConfig.match(/^channel:\s*["']?([^\s"']+)/m)?.[1];
if (packagedChannel !== channel) {
  fail(
    `${packagedUpdaterConfigPath} uses ${packagedChannel ?? 'no channel'}, expected ${channel}`,
  );
}

const metadata = readFileSync(metadataPath, 'utf8');
const metadataVersion = metadata.match(/^version:\s*["']?([^\s"']+)/m)?.[1];
if (metadataVersion !== version) {
  fail(`${metadataPath} describes ${metadataVersion ?? 'no version'}, expected ${version}`);
}
const escapedAppImageName = appImageName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
if (!new RegExp(`^\\s*-?\\s*(?:url|path):\\s*["']?${escapedAppImageName}["']?\\s*$`, 'm').test(metadata)) {
  fail(`${metadataPath} does not reference ${appImageName}`);
}

const evidence = {
  version,
  channel,
  platform: 'linux',
  arch: 'x86_64',
  appImage: {
    name: basename(appImagePath),
    bytes: appImageBytes,
    sha256: sha256(appImagePath),
  },
  blockmap: {
    name: basename(blockmapPath),
    bytes: blockmapBytes,
    sha256: sha256(blockmapPath),
  },
  updateMetadata: basename(metadataPath),
  packagedUpdateChannel: channel,
};

writeFileSync(join('dist', 'linux-canary-evidence.json'), `${JSON.stringify(evidence, null, 2)}\n`);
console.log(`[linux-canary] verified ${appImageName} on the ${channel} channel`);
