import { createHash } from 'node:crypto';
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

function fail(message) {
  console.error(`[linux-release] ${message}`);
  if (process.env.GITHUB_ACTIONS === 'true') {
    console.error(`::error title=Linux release verification::${message}`);
  }
  process.exit(1);
}

function requireFile(path, minimumBytes = 1) {
  if (!existsSync(path)) fail(`missing required artifact: ${path}`);
  const size = statSync(path).size;
  if (size < minimumBytes) fail(`${path} is unexpectedly small (${size} bytes)`);
  return size;
}

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

const version = (process.env.RELEASE_VERSION ?? process.argv[2] ?? '').trim();
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  fail(`expected a stable semantic version, got ${JSON.stringify(version)}`);
}

const packageMetadata = JSON.parse(readFileSync('package.json', 'utf8'));
const packageVersion = packageMetadata.version;
if (packageVersion !== version) {
  fail(`package.json is ${packageVersion}; expected stamped version ${version}`);
}

const expectedDesktopName = 'com.wraeclastledger.app.desktop';
if (packageMetadata.desktopName !== expectedDesktopName) {
  fail(`package.json desktopName is ${packageMetadata.desktopName}; expected ${expectedDesktopName}`);
}

const appImageName = `WraeclastLedger-${version}-x86_64.AppImage`;
const appImagePath = join('dist', appImageName);
const metadataPath = join('dist', 'latest-linux.yml');
const packagedUpdaterConfigPath = join('dist', 'packaged-app-update.yml');
const packagedClipboardHelperPath = join('dist', 'packaged-wl-proton-clipboard.exe');
const packagedDesktopPath = join('dist', expectedDesktopName);

const appImageBytes = requireFile(appImagePath, 50 * 1024 * 1024);
requireFile(metadataPath, 100);
requireFile(packagedUpdaterConfigPath, 20);
const desktopLauncherBytes = requireFile(packagedDesktopPath, 100);
const clipboardHelperBytes = requireFile(packagedClipboardHelperPath, 10 * 1024);
const clipboardHelperHeader = readFileSync(packagedClipboardHelperPath).subarray(0, 2).toString('ascii');
if (clipboardHelperHeader !== 'MZ') fail(`${packagedClipboardHelperPath} is not a Windows executable`);
const desktopLauncher = readFileSync(packagedDesktopPath, 'utf8');
if (!/^\[Desktop Entry\]$/m.test(desktopLauncher)) {
  fail(`${packagedDesktopPath} is not a desktop entry`);
}
const startupWmClass = desktopLauncher.match(/^StartupWMClass=(.+)$/m)?.[1]?.trim();
if (startupWmClass !== 'com.wraeclastledger.app') {
  fail(`${packagedDesktopPath} uses StartupWMClass=${startupWmClass ?? 'missing'}, expected com.wraeclastledger.app`);
}
for (const channel of ['alpha', 'beta', 'rc']) {
  if (existsSync(join('dist', `${channel}-linux.yml`))) {
    fail(`prerelease ${channel}-linux.yml was generated by a stable build`);
  }
}

const packagedUpdaterConfig = readFileSync(packagedUpdaterConfigPath, 'utf8');
const packagedChannel = packagedUpdaterConfig.match(/^channel:\s*["']?([^\s"']+)/m)?.[1];
if (packagedChannel && packagedChannel !== 'latest') {
  fail(`${packagedUpdaterConfigPath} uses ${packagedChannel}, expected latest or the default channel`);
}

const metadata = readFileSync(metadataPath, 'utf8');
const metadataVersion = metadata.match(/^version:\s*["']?([^\s"']+)/m)?.[1];
if (metadataVersion !== version) {
  fail(`${metadataPath} describes ${metadataVersion ?? 'no version'}, expected ${version}`);
}
const embeddedBlockMapBytes = Number(metadata.match(/^\s*blockMapSize:\s*(\d+)\s*$/m)?.[1]);
if (!Number.isSafeInteger(embeddedBlockMapBytes) || embeddedBlockMapBytes < 100) {
  fail(`${metadataPath} does not describe a valid embedded AppImage block map`);
}
const escapedAppImageName = appImageName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
if (!new RegExp(`^\\s*-?\\s*(?:url|path):\\s*["']?${escapedAppImageName}["']?\\s*$`, 'm').test(metadata)) {
  fail(`${metadataPath} does not reference ${appImageName}`);
}

const evidence = {
  version,
  channel: 'latest',
  platform: 'linux',
  arch: 'x86_64',
  sourceSha: process.env.GITHUB_SHA ?? null,
  appImage: { name: basename(appImagePath), bytes: appImageBytes, sha256: sha256(appImagePath) },
  embeddedBlockMapBytes,
  updateMetadata: basename(metadataPath),
  packagedUpdateChannel: packagedChannel ?? 'latest',
  desktopLauncher: {
    name: basename(packagedDesktopPath),
    bytes: desktopLauncherBytes,
    sha256: sha256(packagedDesktopPath),
    startupWmClass,
  },
  protonClipboardHelper: { bytes: clipboardHelperBytes, sha256: sha256(packagedClipboardHelperPath) },
};

writeFileSync(join('dist', 'linux-release-evidence.json'), `${JSON.stringify(evidence, null, 2)}\n`);
console.log(`[linux-release] verified ${appImageName} on the stable channel`);
